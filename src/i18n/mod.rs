#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parse_aliases_and_unknown_fall_back_to_tr() {
        assert_eq!(Language::parse("en"), Language::En);
        assert_eq!(Language::parse("KK"), Language::Kk);
        assert_eq!(Language::parse("xyz"), Language::Tr);
        assert_eq!(Language::parse(""), Language::Tr);
    }

    #[test]
    fn cycle_visits_every_language() {
        let mut lang = Language::Tr;
        let mut seen = std::collections::BTreeSet::new();
        for _ in 0..Language::all().len() {
            seen.insert(lang.id());
            lang = lang.next();
        }
        assert_eq!(seen.len(), Language::all().len());
        assert_eq!(lang, Language::Tr);
    }

    #[test]
    fn every_language_has_distinct_settings_label() {
        let labels: std::collections::BTreeSet<_> =
            Language::all().iter().map(|l| l.t(Msg::Settings)).collect();
        // Settings labels must be unique across every language.
        assert_eq!(labels.len(), Language::all().len());
    }

    #[test]
    fn error_prefix_detection_covers_all_langs() {
        for lang in Language::all() {
            let msg = format!("{} boom", lang.t(Msg::ErrorPrefix));
            assert!(Language::is_error_message(&msg), "{}", lang.id());
        }
        assert!(!Language::is_error_message("ok"));
    }
}
